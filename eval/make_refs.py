MAX_AUTHORS = 10
ORIGINAL = 38  # the first DOIS entries: the original T6 seed set
TARGET = 400  # seed rows kept: every retracted one, the original set, a seeded sample of the rest


def trim(rows: list[dict], target: int = TARGET, seed: int = 0) -> list[dict]:
    """Keep retracted rows and the original set; fill up to `target` with a seeded sample of
    the others. File order is preserved, so the output is stable."""
    first = set(d.lower() for d in DOIS[:ORIGINAL])
    keep = [r for r in rows if r["retracted"] or r["doi"] in first]
    rest = [r for r in rows if r not in keep]
    picked = random.Random(seed).sample(rest, max(0, min(len(rest), target - len(keep))))
    return [r for r in rows if r in keep or r in picked]


def clean(s: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s)).strip()


def parse_crossref(msg: dict) -> dict:
    authors = []
    for a in msg.get("author", [])[:MAX_AUTHORS]:
        if a.get("family"):
            authors.append(clean(f"{a['family']}, {a.get('given', '')}").rstrip(", "))
        elif a.get("name"):
            authors.append(clean(a["name"]))
    venue = msg.get("container-title") or [None]
    return {
        "doi": msg["DOI"].lower(),
        # a citing manuscript uses the original title, not the "RETRACTED:" banner
        "title": re.sub(r"^RETRACTED( ARTICLE)?:\s*", "", clean(msg["title"][0]), flags=re.I),
        "authors": authors,
        "year": msg["issued"]["date-parts"][0][0],
        "venue": clean(venue[0]) if venue[0] else None,
    }


def crossref_retracted(msg: dict) -> bool:
    return any(u.get("type") == "retraction" for u in msg.get("updated-by", []))


async def fetch(client, doi: str, want_retracted: bool) -> dict | None:
    r = await request(client, "GET", f"https://api.crossref.org/works/{doi}")
    if r.status_code != 200:
        print(f"skip {doi}: crossref {r.status_code}", file=sys.stderr)
        return None
    msg = r.json()["message"]
    try:
        row = parse_crossref(msg)
    except (KeyError, IndexError):  # no title / no issued year: not citable as a test seed
        print(f"skip {doi}: incomplete crossref record", file=sys.stderr)
        return None
    if not (row["title"] and row["authors"] and row["year"]):
        print(f"skip {doi}: missing title/authors/year", file=sys.stderr)
        return None
    retracted = crossref_retracted(msg)
    if not retracted:
        o = await request(client, "GET", f"https://api.openalex.org/works/doi:{doi}")
        retracted = o.status_code == 200 and bool(o.json().get("is_retracted"))
    if retracted != want_retracted:
        print(f"skip {doi}: retracted={retracted}, expected {want_retracted}", file=sys.stderr)
        return None
    row["retracted"] = retracted
    return row


async def main() -> None:
    async with make_client() as client:
        sem = asyncio.Semaphore(4)

        async def one(doi, want):
            async with sem:
                try:
                    return await fetch(client, doi, want)
                except Exception as e:  # network trouble: skip, never invent a row
                    print(f"skip {doi}: {type(e).__name__}", file=sys.stderr)
                    return None

        rows = await asyncio.gather(
            *[one(d, False) for d in DOIS], *[one(d, True) for d in RETRACTED_DOIS]
        )
    # an alias DOI can resolve to a DOI already in the list: keep the first
    uniq = {}
    for r in rows:
        if r:
            uniq.setdefault(r["doi"], r)
    rows = trim(list(uniq.values()))
    OUT.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
    n_ret = sum(r["retracted"] for r in rows)
    print(f"wrote {len(rows)} rows ({n_ret} retracted) to {OUT}")


if __name__ == "__main__":
    asyncio.run(main())
